function genPayoff(
  lower: number,
  upper: number,
  breakeven: number,
  maxProfit: number,
  maxLoss: number,
  isBullSpread: boolean,
  currentPrice: number,
  steps = 80,
): { underlying_price: number; pnl: number }[] {
  const points: { underlying_price: number; pnl: number }[] = [];
  for (let i = 0; i <= steps; i++) {
    const price = lower + ((upper - lower) * i) / steps;
    let pnl: number;
    if (isBullSpread) {
      if (price <= breakeven) pnl = -maxLoss + (price - lower) * (maxProfit + maxLoss) / (breakeven - lower);
      else if (price <= upper) pnl = -maxLoss + (price - lower) * (maxProfit + maxLoss) / (upper - lower);
      else pnl = maxProfit;
    } else {
      if (price >= breakeven) pnl = -maxLoss + (upper - price) * (maxProfit + maxLoss) / (upper - breakeven);
      else if (price >= lower) pnl = -maxLoss + (upper - price) * (maxProfit + maxLoss) / (upper - lower);
      else pnl = maxProfit;
    }
    points.push({
      underlying_price: Math.round(price * 100) / 100,
      pnl: Math.round(pnl * 100) / 100,
    });
  }
  return points;
}

